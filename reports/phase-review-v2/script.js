function fmt(sec) {
  return sec >= 60 ? `${Math.floor(sec / 60)} 分${sec % 60 ? ` ${sec % 60} 秒` : '鐘'}` : `${sec} 秒`;
}

function notes(i) {
  const s = SLIDES[i];
  const out = [`【講者】${s.speaker}　【時間】約 ${fmt(s.seconds)}`, ''];
  if (s.actions) out.push('【操作】', ...s.actions.map((a) => '・' + a), '');
  out.push('【講稿】', ...s.say, '');
  if (s.caution) out.push('【注意】', ...s.caution.map((c) => '・' + c));
  return out.join('\n');
}

function markdown() {
  const total = SLIDES.reduce((n, s) => n + s.seconds, 0);
  const lines = [
    '# 階段成果檢視講稿（v2）',
    '',
    `第 02 組。對應 [phase-review-v2.pptx](phase-review-v2.pptx)，同一份內容也在 PPTX 的講者備註裡。${SLIDES.length} 張投影片約 ${Math.round(total / 6) / 10} 分鐘（含兩段示範），問答 5 分鐘，緩衝 1 分鐘，總長 20 分鐘。`,
    '',
    '講者分配沿用原本的建議分工，**實際分工待兩位確認**。講稿是說法參考，請先自己操作一次、用自己的話講，不要逐字照念。',
    '',
    '| 頁 | 主題 | 講者 | 時間 |',
    '|---|---|---|---|',
    ...SLIDES.map((s, i) => `| ${i + 1} | ${s.title} | ${s.speaker} | ${fmt(s.seconds)} |`),
    '',
  ];
  SLIDES.forEach((s, i) => {
    lines.push(`## ${i + 1}. ${s.title}`, '', `**${s.speaker} · 約 ${fmt(s.seconds)}**`, '');
    if (s.actions) lines.push('操作：', '', ...s.actions.map((a) => `- ${a}`), '');
    lines.push(...s.say.flatMap((p) => [p, '']));
    if (s.caution) lines.push(...s.caution.map((c) => `> 注意：${c}`), '');
  });
  lines.push('## 問答準備', '');
  for (const [q, a] of QA) lines.push(`**${q}**`, '', a, '');
  return lines.join('\n');
}

module.exports = { SLIDES, notes, markdown };
